// Enumerated from a live `tools/list` plus a `tool_search` sweep of all 15 categories against
// Binance's own MCP server on 2026-09-05, and committed so a reviewer can diff it rather than
// take it on trust. 256 names.
//
// Its job is to make the *unknown* case safe. `effectOf` used to answer READ for anything it did
// not recognise, which meant the classification failed OPEN: the day a futures or margin scope is
// granted and `futures_usds.newOrder` appears on the surface, it would have passed through the
// Governor ungated. That was only harmless because Binance was refusing those calls for us — the
// exchange protecting the operator, not this project.
//
// So an unrecognised tool is now treated as a WRITE and refused by gate 18. A false positive costs
// one line in this file; a false negative is an ungated order. Note what this catalogue actually
// contains: all 164 futures and margin entries in it are READS (query/get/list/klines/history),
// because the futures and margin scopes were deliberately declined at the consent screen. There is
// no enumerated futures write surface to allow, which is exactly why an unknown one must not be.

